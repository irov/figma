#include "JsonDocument.h"

namespace Figma
{
    //////////////////////////////////////////////////////////////////////////
    JsonDocument::JsonDocument()
        : m_root( nullptr )
    {
    }
    //////////////////////////////////////////////////////////////////////////
    JsonDocument::~JsonDocument()
    {
        if( m_root != nullptr )
        {
            js_free( m_root );
            m_root = nullptr;
        }
    }
    //////////////////////////////////////////////////////////////////////////
    js_element_t ** JsonDocument::getAddress()
    {
        return &m_root;
    }
    //////////////////////////////////////////////////////////////////////////
    const js_element_t * JsonDocument::getRoot() const
    {
        return m_root;
    }
    //////////////////////////////////////////////////////////////////////////
}
